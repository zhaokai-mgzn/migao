-- 逐条说明：
--   · `name IN (...)` —— **只改这三道**（冻结集合；`配料` 是部位级、`打包` 早已是 `set`，
--     两者都不在本集合里 ⇒ 一字不动）；
--   · `source IN ('占位待确认','推算')` —— **只改播种来源**（V62 冻结口径；`NULL` = 商家自建/
