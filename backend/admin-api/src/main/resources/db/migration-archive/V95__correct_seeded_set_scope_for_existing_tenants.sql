--   · `scope = 'position'` —— 幂等守卫（已是 `set` 的行整条跳过，第二次执行 0 行）；
--   · 显式写列（`scope` + `updated_at`）—— 不写 `SET (scope) = ...` 之类的隐式形态，也不碰
--     任何其它列（`unit_price` 等计件口径列一字不动）。
UPDATE production_operations
   SET scope = 'set',
       updated_at = NOW()
 WHERE name IN ('外帘打卷', '外帘装袋', '外帘发货')
   AND source IN ('占位待确认', '推算')
   AND scope = 'position';
