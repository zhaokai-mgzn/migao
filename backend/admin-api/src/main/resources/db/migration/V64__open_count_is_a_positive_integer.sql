-- 开数（`order_items.open_count`）语义澄清：**开数（正整数）**，不是固定枚举（issue #4387 判据 1）
--
-- ## 为什么要有这个迁移（缺陷形态 = 权威注释与用户口径冲突）
-- V63 把 `open_count` 的列注释写成「1 单开 / 2 双开·对开 / 4 四开」——**缺 3（三开）**，
-- 而用户口径（2026-09-19）明确含三开：
--   「订单上还有定高买宽，定宽买高，单开，双开，三开这些信息，也要在订单上体现的。」
-- 列注释是本列语义的**权威**（`OrderLineCraftFields` 类注释明写「本类不是真值源：列语义的
-- 权威在 DB 列注释」）⇒ 注释里没有 3，读它的人（人与 agent 都一样）会当成枚举去实现，
-- 于是三开在写面被过滤掉、在展示面被当成未知值。**改注释不是文档洁癖，是改契约**。
--
-- ## 为什么不是改 V63（迁移不可变，issue #4235）
-- `MigrationRunner` 的 `schema_migrations` 按**文件名**记，已应用迁移整份 skip ⇒
-- 改 V63 在存量环境**永远不生效**，而任何静态守卫反而转绿（CI 全绿、功能静默缺失）。
-- ⇒ 语义修正一律走**新迁移**（本文件），V63 一个字不动。
--
-- ## 取值口径（放开，不设约束）
-- 开数是**正整数**（1 / 2 / 3 / 4 …），不是固定枚举 ⇒ 本迁移**不加 CHECK、不加默认值**：
-- 加 CHECK 会把「5 开」这类真实需求变成写库失败（V63 已裁定「不设必填校验」，本迁移同口径）。
-- 仍然成立的下游校验（**不在本列上**）：真值源 §8「对开总折数必须为偶数」由算料侧
-- （`curtain_calc.derive_pleat_count`）按开数取整保证，与本列取值域无关。
--
-- ## 幂等（MigrationRunner 要求所有 SQL 可重复执行）
-- `COMMENT ON COLUMN` 是**幂等 DDL**（重复执行结果相同，不报错）。
--
-- ## bootstrap 终态同步
-- `docs/sql/schema.sql` 的同列注释已同步为本文件的终态（bootstrap 路径**不跑迁移链**，
-- 只写迁移 = 新建库的列注释仍是旧的，#3270 形态）。

COMMENT ON COLUMN order_items.open_count IS
    '打开方式（**开数**，V63；issue #4387 判据 1）：**正整数** 1 单开 / 2 双开·对开 / 3 三开 / 4 四开 …，不是固定枚举。对开总折数必须为偶数（真值源 §8，由算料侧按开数取整保证）；可空';
