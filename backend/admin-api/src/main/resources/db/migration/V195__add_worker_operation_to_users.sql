-- 工人档案绑定一道**逻辑工序**（issue #7749，用户 2026-10-25 裁定）—— `users.worker_operation`
--
-- ## 一句话
-- 一个工人对应一道工序：生产时扫一次码，系统按**这位工人**绑定的工序自动选中，
-- 工人只点【报工】，不再在屏上选工序（用户逐字：「工人扫码后直接报工，通过工人自动选择工序」）。
--
-- ## 为什么存**逻辑工序名**（`韩褶`）而不是工序库行 id（`韩褶-布` / `韩褶-纱`）
-- 用户 2026-10-25 选定粒度 =「按逻辑工序（如「韩褶」，布帘/纱帘通用）」：
-- 工序库里同一道活按部位拆成多行（`精裁-布` / `精裁-纱`，见 V49/V56 的旧名口径），
-- 而一个车位工人本来就**布纱都做** ⇒ 绑到某一行会让「扫纱帘没活」变成常态。
-- 逻辑名 = `ProductionOperationQueryService.logicalOperationName` 的既有翻译结果（**不新增第二份映射表**）。
--
-- ## 三态
--   · NULL = **未绑定** ⇒ 保持改前行为（系统推断下一道 + 工序选择器）。**存量行与新建默认值**
--     （本迁移**不回填**任何行 —— 回填只能靠猜「这个工人做哪道」，猜错就是把计件记到别人头上）。
--   · '韩褶' = 只报这一道；本件没有这道 / 已做完 ⇒ 明确告知工人，**不**静默改报别的工序。
--
-- ## 只存名字、不建外键（与 V193 同口径）
-- 工序库行可改名/停用/软删；档案绑的是「岗位」这一事实，不是某一行数据。
-- 写面在服务层校验「该逻辑工序在本租户**当前**工序库里存在」（`WorkerAdminService`），
-- 读面（扫码）解析不到就退回「未绑定」口径并把状态如实下发给工人端 —— 不猜、不静默。
--
-- ## bootstrap 终态同步（同 V99/V108/V127/V133/V170/V193 纪律）
-- 新建库路径**不跑历史迁移链** ⇒ `backend/admin-api/src/main/resources/db/init/schema.sql`
-- 已同步本文件终态（列 + 注释）。只改一处 ⇒ 新建库缺列。
--
-- ## 回滚（**新迁移，不删本文件**）
-- ```sql
-- -- V195__rollback_worker_operation.sql（本单只登记，不落码）
-- -- ALTER TABLE users DROP COLUMN IF EXISTS worker_operation;
-- ```
-- ⚠️ 回滚是**有损**的：已绑定的工序会一并消失（工人回到「扫码后自己选工序」的旧形态）。
--
-- ## 显式事务
-- `MigrationRunner` 对每个迁移文件跑单事务；本文件只有一条 DDL（PostgreSQL 的 DDL 可事务）。
ALTER TABLE users ADD COLUMN IF NOT EXISTS worker_operation VARCHAR(64);

COMMENT ON COLUMN users.worker_operation IS
    '工人档案绑定的逻辑工序（V195，issue #7749；用户 2026-10-25 裁定「一个工人对应一个工序」）。'
    'NULL = 未绑定（存量/新建默认，本迁移不回填 ⇒ 保持系统推断 + 工序选择器）；'
    '非空 = 逻辑工序名（如 韩褶，工序库的 韩褶-布/韩褶-纱 归并成同一逻辑名）。'
    '用途：扫码报工时按本列自动选中该工人的工序（WorkerProductionController / ProductionScanService），'
    '写面校验「本租户工序库里存在该逻辑工序」；不是权限码，不参与授权判定。';
