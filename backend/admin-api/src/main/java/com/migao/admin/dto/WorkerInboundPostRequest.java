package com.migao.admin.dto;

import lombok.Data;

/**
 * 工人提交过账请求（issue #5052 P1，设计 §5.2 / §6.5）。
 *
 * <p>字段面 = <b>一个</b> {@code confirmed}。</p>
 *
 * <h3>为什么「人工确认」必须是一条服务端可见的判据（设计 §6.5 / §11.1 第 5 条）</h3>
 * <p>裁定 4 = 「AI 识别 + 人工确认」，**不做免确认**。而「工人点过按钮」是**前端形态**、
 * 服务端看不见 ⇒ 服务端必须能区分「有工人确认」与「无工人确认」的提交。
 * 本类就是那个区分点：缺它 / 非 {@code true} ⇒ <b>409 且一行库存都不动</b>
 * （未确认不落库）。</p>
 *
 * <p><b>边界（如实登记）</b>：该标记是**传输层**判据（请求体显式携带），不是**持久化**记录 ——
 * 落一条服务端确认记录需要在 {@code inbound_orders} 上加列（属迁移面，超出 P1 的写面）。
 * 它挡住的是「流程里悄悄跳过确认」（页面漏传 / 脚本直接调 post），
 * <b>不是</b>「拿到工人 session 的恶意客户端伪造 true」——后者由「零商家权限 + 窄接口 +
 * 幂等 + 台账留痕」那几条承担（设计 §9.1：BYOD 下服务端是唯一防线）。</p>
 */
@Data
public class WorkerInboundPostRequest {

    /** 人工确认标记：必须**显式** {@code true}（缺省 / false / null ⇒ 409，未确认不落库） */
    private Boolean confirmed;
}
