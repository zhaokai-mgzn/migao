/**
 * 订单的**安装信息**（issue #7856）—— 前端口径的唯一一处。
 *
 * 两个字段（口径已定，键名不改）：
 * - **安装小区**（订单级，整单一个值）：这批帘子**最终装进的那一户人家所在的小区**
 *   （可连带楼栋 / 单元 / 门牌）。🔴 **不是收货地址**（货是发给下单的窗帘店）——
 *   两个地址是**两个事实**，不合并、不互相回填；
 * - **安装位置**（件级：一行 = 一个部位 = 一扇窗）：这一扇窗装在那户人家的哪个空间
 *   （主卧 / 阳台 …）。🔴 **不是**部位 / 帘种（布帘 / 纱帘 = `curtainType`）。
 *
 * 两个都是**只存只印**的附注（水洗唛 / 发货标签 / 入库标签）：不参与计价 / 算料 / 派工 / 库存，
 * 缺值不打印。落点 = `order_items.processing_info` 的 `installCommunity`（服务端扇出到每行）/
 * `installRoom`（件级）—— 不是数据库列、也不是 item 一级字段。
 *
 * 为什么上限只在**前端**这一处声明：服务端（`OrderInstallInfo`）超长是 **422 硬拒** ⇒
 * 录入控件必须先在 `maxLength` 挡住（别让商家敲完才发现被拒）；两个录入面（下单页 / 改单弹层）
 * 共用同一份常量，避免"一个面 40、另一个面 30"这种静默漂移。
 */

/** 安装小区上限（可带楼栋/单元/门牌，故比位置宽）—— 与 `OrderInstallInfo.COMMUNITY_MAX_LENGTH` 同值 */
export const INSTALL_COMMUNITY_MAX_LENGTH = 40

/** 安装位置上限（「主卧」「客厅」「阳台」这类空间名）—— 与 `OrderInstallInfo.ROOM_MAX_LENGTH` 同值 */
export const INSTALL_ROOM_MAX_LENGTH = 12
